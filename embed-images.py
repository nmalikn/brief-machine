#!/usr/bin/env python3
"""Rebuilds images.js from the memes/ folder. Run after adding or removing a meme:

    python3 embed-images.py

Browsers won't let a double-clicked page read pixels from image files, so the
pictures are embedded as data URIs. That is what makes color picking work.
"""
import base64
import json
import pathlib

ROOT = pathlib.Path(__file__).parent
TYPES = {".jpg": "image/jpeg", ".jpeg": "image/jpeg", ".png": "image/png", ".webp": "image/webp"}

images = {}
for path in sorted((ROOT / "memes").iterdir()):
    if path.suffix.lower() in TYPES:
        encoded = base64.b64encode(path.read_bytes()).decode()
        images[f"memes/{path.name}"] = f"data:{TYPES[path.suffix.lower()]};base64,{encoded}"

(ROOT / "images.js").write_text(
    "// Generated by embed-images.py. Don't edit by hand.\n"
    f"const BRIEF_IMAGES = {json.dumps(images, indent=2)};\n"
)
print(f"Embedded {len(images)} images")
